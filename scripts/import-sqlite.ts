// One-time import of the old Flask app's SQLite database into D1.
//
//   ENCRYPTION_KEY=<same key as the Worker secret> node scripts/import-sqlite.ts path/to/journals.db > migrate.sql
//   npx wrangler d1 execute DB --remote --file migrate.sql      (use --local to try it first)
//
// Passwords are NOT imported (login is by emailed link now). Journal text is encrypted here
// before it ever reaches D1. Unredeemed registration codes become invites.
import { DatabaseSync } from "node:sqlite";
import { encrypt, importKey } from "../src/crypto.ts";

const [dbPath] = process.argv.slice(2);
if (!dbPath || !process.env.ENCRYPTION_KEY) {
  console.error("usage: ENCRYPTION_KEY=... node scripts/import-sqlite.ts journals.db > migrate.sql");
  process.exit(1);
}
const key = await importKey(process.env.ENCRYPTION_KEY);
const db = new DatabaseSync(dbPath, { readOnly: true });

const q = (v: unknown): string => (v === null || v === undefined ? "NULL" : typeof v === "number" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const cols = (db.prepare("PRAGMA table_info(journals)").all() as { name: string }[]).map((c) => c.name);
if (!cols.includes("resp_sent")) {
  console.error(`journals has no resp_sent column (found: ${cols.join(", ")}). Check what resp_draft means before importing.`);
  process.exit(1);
}

type User = { id: number; admin: number; email: string; name: string | null; joined: string };
type Journal = { id: number; user_id: number; resp_id: number | null; content: string | null; response: string | null; time_crte: string; time_updt?: string | null; time_resp: string | null; submitted: number; resp_sent: number };
type Code = { email: string; admin: number; valid: string | null };

const users = db.prepare("SELECT id, admin, email, name, joined FROM users").all() as User[];
const out: string[] = ["-- generated by scripts/import-sqlite.ts"];

for (const u of users)
  out.push(`INSERT INTO users (id, email, name, admin, joined) VALUES (${u.id}, ${q(u.email.trim().toLowerCase())}, ${q(u.name)}, ${u.admin ? 1 : 0}, ${q(u.joined)});`);

for (const j of db.prepare("SELECT * FROM journals").all() as Journal[]) {
  const content = await encrypt(key, j.content, `journals.content:${j.id}`);
  const response = await encrypt(key, j.response, `journals.response:${j.id}`);
  out.push(
    `INSERT INTO journals (id, user_id, resp_id, content, response, time_crte, time_updt, time_resp, submitted, resp_sent) VALUES (${j.id}, ${j.user_id}, ${q(j.resp_id)}, ${q(content)}, ${q(response)}, ${q(j.time_crte)}, ${q(j.time_updt ?? null)}, ${q(j.time_resp)}, ${j.submitted ? 1 : 0}, ${j.resp_sent ? 1 : 0});`,
  );
}

const have = new Set(users.map((u) => u.email.trim().toLowerCase()));
for (const c of db.prepare("SELECT email, admin, valid FROM codes WHERE valid IS NOT NULL").all() as Code[]) {
  const email = c.email.trim().toLowerCase();
  if (!have.has(email)) out.push(`INSERT OR IGNORE INTO invites (email, admin) VALUES (${q(email)}, ${c.admin ? 1 : 0});`);
}

console.log(out.join("\n"));
console.error(`${users.length} users, ${out.filter((l) => l.startsWith("INSERT INTO journals")).length} journals, ${out.filter((l) => l.includes("INTO invites")).length} invites`);
